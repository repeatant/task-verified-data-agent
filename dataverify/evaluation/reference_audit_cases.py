"""Fault-injection scenarios for graph behavior, not estimates of model accuracy."""

from copy import deepcopy
from dataclasses import dataclass

from dataverify.agent.discovery_model import ScriptedReviewModel
from dataverify.agent.graph_model import ScriptedGraphModel
from dataverify.evaluation.discovery_cases import ELIGIBLE, data, get_discovery_cases
from dataverify.evaluation.discovery_roles import AuthoredReviewModel, authored_attribution
from dataverify.verification.discovery_runtime import DiscoveryTask
from dataverify.verification.probe_runtime import ProbeData


@dataclass(frozen=True)
class AuditScenario:
    name: str
    task: DiscoveryTask
    source: ProbeData
    initial_sql: str
    final_sql: str
    reference_plan: dict
    independent_plan: dict
    target: str | None
    expected_rows: list
    expected_status: str = "reviewed"
    confirmed_examples: tuple = ()
    known_limitation: bool = False

    def roles(self):
        writer = ScriptedGraphModel(
            [
                {"sql": self.initial_sql, "task_id": self.task.task_id},
                {"sql": self.final_sql, "task_id": self.task.task_id},
            ]
        )
        actions = [deepcopy(self.reference_plan)]
        if self.target:
            actions.append(authored_attribution(self.task, self.target))
        actions.append(
            {"action": "finish", "reason": "Authored behavior check, not model evidence."}
        )
        return (
            writer,
            AuthoredReviewModel(actions),
            ScriptedReviewModel([deepcopy(self.independent_plan)]),
        )


def audit_scenarios() -> list[AuditScenario]:
    case = get_discovery_cases()[0]
    good = case.offline_plan()
    rounded = deepcopy(good)
    rounded["reference"] = "[[round(" + case.offline_reference[2:-2] + ",2)]]"
    wrong_grain = deepcopy(good)
    valid = f"[r['amount'] for r in tables['order_lines'] if {ELIGIBLE}]"
    wrong_grain["reference"] = f"values={valid}\n[[sum(values)/len(values) if values else 0]]"
    rounded_sql = (
        "SELECT ROUND(mean_value,2) FROM ("
        + case.good_sql.replace("COALESCE(AVG(net),0)", "COALESCE(AVG(net),0) AS mean_value")
        + ")"
    )
    precision_source = data([10, 10, 11])
    scenarios = [
        AuditScenario(
            "wrong_reference_rounding",
            case.task,
            precision_source,
            case.good_sql,
            case.good_sql,
            rounded,
            good,
            "reference",
            [[31 / 3]],
        ),
        AuditScenario(
            "wrong_sql_grain",
            case.task,
            case.source,
            case.bad_sql,
            case.good_sql,
            good,
            good,
            "candidate",
            case.expected,
        ),
        AuditScenario(
            "correct_pair",
            case.task,
            precision_source,
            case.good_sql,
            case.good_sql,
            good,
            good,
            None,
            [[31 / 3]],
        ),
    ]
    explicit = DiscoveryTask(case.name, case.task.question + "最终平均值四舍五入保留两位小数。")
    explicit_plan = deepcopy(rounded)
    explicit_plan["reference"] = explicit_plan["reference"].replace("round(", "round_half_up(")
    explicit_plan["basis"] = [{"source": "question", "quote": explicit.question}]
    scenarios.append(
        AuditScenario(
            "requested_rounding",
            explicit,
            precision_source,
            rounded_sql,
            rounded_sql,
            explicit_plan,
            explicit_plan,
            None,
            [[10.33]],
        )
    )
    # An externally supplied checked example is intentionally NOT generated by
    # an agent. Its expected value stays outside writer and blind audit contexts;
    # the attribution role may see the executed caller-confirmed evidence.
    anchor = (
        {
            "name": "business_checked_example",
            "data": case.source.to_dict(),
            "expected": case.expected,
            "source": "Caller-confirmed order-level arithmetic",
        },
    )
    scenarios.extend(
        [
            AuditScenario(
                "correlated_error_with_anchor",
                case.task,
                case.source,
                case.bad_sql,
                case.good_sql,
                wrong_grain,
                wrong_grain,
                "ambiguous",
                case.expected,
                "needs_clarification",
                anchor,
            ),
            AuditScenario(
                "correlated_error_without_anchor",
                case.task,
                case.source,
                case.bad_sql,
                case.good_sql,
                wrong_grain,
                wrong_grain,
                None,
                case.expected,
                known_limitation=True,
            ),
            AuditScenario(
                "unsupported_attribution",
                case.task,
                precision_source,
                case.good_sql,
                case.good_sql,
                rounded,
                good,
                "ambiguous",
                [[31 / 3]],
                "needs_clarification",
            ),
        ]
    )
    for name, expression in (
        ("wrong_reference_unit", "[[ (" + case.offline_reference[2:-2] + ") / 100 ]]"),
        (
            "wrong_reference_filter",
            case.offline_reference.replace(ELIGIBLE, f"({ELIGIBLE}) and r['amount'] > 0"),
        ),
    ):
        wrong = deepcopy(good)
        # Each injected calculation implements a plausible but unauthorized
        # business interpretation; neither change is a runtime special case.
        wrong["reference"] = expression
        scenarios.append(
            AuditScenario(
                name,
                case.task,
                case.source,
                case.good_sql,
                case.good_sql,
                wrong,
                good,
                "reference",
                case.expected,
            )
        )
    return scenarios
